// Welche Warengruppen garen und damit einen Garverlust haben (C5: Branchenwert rund 15 % als sichtbare Schätzung).
export const GARVERLUST_START = { fleisch: 0.15, fisch: 0.15 };

// Steuersatz je Warengruppe (Prüfung Befund 7): Speisen 7 %, Getränke 19 %. Gilt für das fertige Gericht über seine Hauptzutat.
export const STEUER_JE_GRUPPE = { getraenk: 0.19, spirituose: 0.19 };

export function bereicheFuer(formatId, kuechen) {
  const set = new Set();
  for (const k of kuechen || []) for (const b of BEREICHE_JE_KUECHE[k] || []) set.add(b);
  for (const b of BEREICHE_JE_BETRIEB[formatId] || []) set.add(b);
  // Grundzutaten und Verpackung braucht jeder, alkoholfrei fast jeder
  set.add("grundzutaten"); set.add("verpackung"); set.add("alkoholfrei");
  return [...set].filter((b) => KATALOG[b]);
}

export function vorlagenFuer(formatId, kuechen) {
  const raus = [];
  for (const b of bereicheFuer(formatId, kuechen)) {
    for (const v of VORLAGEN[b] || []) if (!raus.some((x) => x.name === v.name)) raus.push({ ...v, bereich: b });
  }
  return raus;
}
