// Klein schreiben, türkische Sonderzeichen und deutsche Umlaute falten: „Soğan“, „sogan“, „SOGAN“ → „sogan“.
export function normalisieren(s) {
  return String(s ?? "")
    .replace(/[İIı]/g, "i") // vor toLowerCase: sonst wird „İ“ zu „i̇“ und „ı“ bleibt stehen
    .toLowerCase()
    .replace(/ß/g, "ss")
    .normalize("NFD").replace(/[̀-ͯ]/g, "") // ğ ş ç ö ü ä é … → Grundbuchstabe
    .trim();
}

// Je Artikelname einmal vorbereitet: [deutscher Name, …Suchnamen], alles schon normalisiert.
const VORBEREITET = new Map();
function begriffe(name) {
  if (!VORBEREITET.has(name)) VORBEREITET.set(name, (SUCHNAMEN[name] || []).map(normalisieren));
  return VORBEREITET.get(name);
}

// Rang für die Suche: 0 = deutscher Name passt, 1 = nur ein Suchname passt, -1 = kein Treffer.
// q muss schon normalisiert sein (normalisieren(eingabe)).
export function suchRang(name, q) {
  if (!q) return -1;
  if (normalisieren(name).includes(q)) return 0;
  return begriffe(name).some((b) => b.includes(q)) ? 1 : -1;
}
